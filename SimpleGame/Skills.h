#pragma once

//
// 동행자의 싸움법.
//
// 깨워서 데려가는 사람은 종탑까지 가는 동안 제 일로 함께 싸운다.
// 대장장이는 망치를 내려치고, 사냥꾼은 활을 쏘고, 수도승은 기도로
// 플레이어를 지킨다. 모두가 불씨를 쏘면 누구를 데려가든 같아지므로,
// 일부러 방식이 서로 겹치지 않게 했다.
//
//   근접 광역   대장장이, 종지기 노인 — 둘레의 적을 한꺼번에
//   근접 단일   떠돌이 병사           — 가까운 적을 빠르게 연달아
//   원거리 단일 사냥꾼                — 멀리 있는 적을 하나씩
//   원거리 광역 광부                  — 무리 한가운데에 폭약
//   장판        약초꾼, 필경사        — 땅에 깔아 두고 그 안의 적을 묶는다
//   회복·보호   수도승                — 싸우지 않고 플레이어를 살린다
//
// 누가 동행하느냐에 따라 같은 길도 다르게 싸워야 한다. 사냥꾼과 함께면
// 멀찍이 서서 쏘게 하고, 대장장이와 함께면 적을 끌어와 둘레에 모아야 한다.
//
// 번호는 대사(Dialogue.cpp)와 특성(Perks.cpp)의 순서와 같다. 말을 건
// 사람, 함께 싸우는 사람, 마을에 남아 돕는 사람이 모두 같은 사람이다.
//
namespace Skills
{
	struct Info
	{
		const char* who;        // 직업
		const char* name;       // 스킬 이름. 쓸 때 머리 위에 뜬다
		const char* style;      // 근접 광역, 원거리 단일 …
		const char* effect;     // 한 줄 설명
		float cooldown;         // 다시 쓰기까지(초)
		float reach;            // 이 거리 안에 적이 있어야 쓴다(px). 수도승은 해당 없음
		bool announce;          // 쓸 때 이름을 띄울지. 자주 쓰는 것은 띄우지 않는다
		float tint[3];          // 이 사람의 빛깔. 스킬 효과와 HUD에 쓴다
	};

	int Count();
	const Info& At(int profession);
}
