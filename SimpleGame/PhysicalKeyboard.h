#pragma once

//
// 키보드를 "글자"가 아니라 "자리"로 읽는다.
//
// GLUT는 키를 글자로 넘겨준다. 그런데 한글 입력 상태에서 F 자리 키를 누르면
// 운영체제는 'f'가 아니라 'ㄹ'을 보낸다. 게임은 그걸 F로 알아보지 못하고,
// 플레이어 입장에서는 "공격이 갑자기 안 나간다". 채팅에서 한글을 쓰다가
// 게임 창으로 넘어오면 한글 상태가 그대로 따라오므로 자주 일어난다.
//
// 게임의 조작은 글자가 아니라 키보드 위의 자리에 묶여야 맞다. 한글이든
// 영문이든, 쿼티든 드보락이든 WASD는 왼손 아래 그 네 자리여야 한다.
//
// macOS에서는 앱 자신의 키 이벤트를 창보다 먼저 받아 보는 로컬 모니터를
// 건다. 여기서는 입력기(IME)를 거치기 전의 물리 키 코드가 보인다.
// 남의 앱 키를 엿보는 것이 아니므로 손쉬운 사용 권한이 필요 없다.
//
// 알아본 키는 영문 소문자로 바꿔 GLUT 콜백에 그대로 넘기고, 원래 이벤트는
// 삼킨다. 그래야 영문 상태에서 같은 키가 두 번 들어가지 않는다
// (P·M·B 같은 켜고 끄는 키가 두 번 눌려 제자리로 돌아오는 일을 막는다).
//
// Windows에서는 아무것도 하지 않는다(GLUT 경로를 그대로 쓴다).
//
typedef void (*KeyHandler)(unsigned char key, int x, int y);

// 창을 만든 뒤에 한 번 부른다. 성공하면 true.
bool InstallPhysicalKeyboard(KeyHandler down, KeyHandler up);
